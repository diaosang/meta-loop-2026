def main():
    book=SOURCE/'court-voice-data.json'
    data=json.loads(book.read_text(encoding='utf-8'))
    text=(SOURCE/'build_court_voice_data.py').read_text(encoding='utf-8-sig')
    revisions=[]
    def change(row,new):
        nonlocal text
        old=row['reply']
        if old!=new:
            assert old in text, row['id']
            assert "'" not in new and '\n' not in new
            text=text.replace(old,new)
        revisions.append({'id':row['id'],'category':row['category'],'topic':row['topic'],
                          'personality':row.get('personality','通用'),'before':old,'after':new})
        row['reply']=new
    for (category,topic),lines in GROUPS.items():
        candidates=[r for r in data['rows'] if r['category']==category and r['topic']==topic and r['role']=='any'
                    and not r.get('personality') and not r.get('moods') and r.get('positive') is not False]
        assert len(candidates)==len(lines),(category,topic,len(candidates),len(lines))
        for r,line in zip(candidates,lines):change(r,line)
    for r in data['rows']:
        if r['semantic'].startswith('voice-'):
            mapping=PERSONAL_LISTEN if r['category']=='care' else PERSONAL_RECENT if r['category']=='chat' else PERSONAL_OPINION if r['category']=='probe' else None
            if mapping:change(r,mapping[r['personality']])
        elif r['topic']=='family' and r.get('personality'):change(r,FAMILY[r['personality']])
        elif r['category']=='care' and r.get('moods'):change(r,MOODS[r['moods'][0]])
    (SOURCE/'build_court_voice_data.py').write_text(text,encoding='utf-8')
    runpy.run_path(str(SOURCE/'build_court_voice_data.py'),run_name='__main__')
    report=SOURCE/'natural-talk-revision.json'
    if report.exists():
        original={r['id']:r['before'] for r in json.loads(report.read_text(encoding='utf-8'))['rows']}
        for r in revisions:r['before']=original.get(r['id'],r['before'])
    result={'revision':'13.1','changedOrdinaryResponses':len(revisions),'rows':revisions}
    report.write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
    followups={'version':'13.1','rows':{f'care:listen:any:{key}':[{'say':p,'reply':r} for p,r in pairs] for key,pairs in FOLLOWUPS.items()}}
    (SOURCE/'listen-followups.json').write_text(json.dumps(followups,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps({'ordinaryResponsesRewritten':len(revisions)},ensure_ascii=False))

if __name__=='__main__':main()
