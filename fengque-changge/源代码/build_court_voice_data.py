def bank(category, topic, text, role='any', **conditions):
    for i, line in enumerate(text.strip().splitlines()):
        if not line.strip():
            continue
        semantic, reply = line.strip().split('|', 1)
        rows.append(dict(id=f'{category}:{topic}:{role}:{semantic}', category=category,
                         topic=topic, role=role, semantic=semantic, reply=reply, **conditions))

